// Helper generator functions
export function generateRandomAppId(schoolName: string, state: string): string {
  const cleanName = schoolName
    .replace(/[^a-zA-Z]/g, '')
    .toUpperCase()
    .substring(0, 5) || 'SCH';
  const cleanState = state
    .replace(/[^a-zA-Z]/g, '')
    .toUpperCase()
    .substring(0, 3) || 'NG';
  const rand = Math.floor(1000 + Math.random() * 9000);
  return `CF-2026-${cleanName}-${cleanState}-${rand}`;
}

export function generateAppSecret(): string {
  const chars = '0123456789abcdef';
  let result = 'cf_sec_live_';
  for (let i = 0; i < 32; i++) {
    result += chars[Math.floor(Math.random() * chars.length)];
  }
  return result;
}

export function generatePublishableKey(): string {
  const chars = '0123456789abcdef';
  let result = 'cf_pub_live_';
  for (let i = 0; i < 16; i++) {
    result += chars[Math.floor(Math.random() * chars.length)];
  }
  return result;
}

export function generateLicenseHash(): string {
  const chars = '0123456789abcdef';
  let result = 'sha256:';
  for (let i = 0; i < 64; i++) {
    result += chars[Math.floor(Math.random() * chars.length)];
  }
  return result;
}

