/**
 * Check if an auth account has a specific permission
 */
export function checkAccountPermission(
  account: UserAuthAccount,
  permissionKey: keyof IAMPermissionMatrix,
  rolesRegistry: AdminRoleDefinition[]
): boolean {
  // Principal Admin is root super admin with all permissions
  if (account.primaryRole === 'principal_admin' || account.assignedAdminRoles.includes('principal_admin')) {
    return true;
  }

  // Iterate over assigned admin roles
  for (const roleType of account.assignedAdminRoles) {
    const roleDef = rolesRegistry.find(r => r.roleType === roleType);
    if (roleDef && roleDef.permissions[permissionKey]) {
      return true;
    }
  }

  // Default teacher permissions if no admin role matches
  return TEACHER_DEFAULT_PERMISSIONS[permissionKey] ?? false;
}
